//! The verified HKMA dataset table — extracted into its own module so the
//! connector logic in [`super::hkma`] stays navigable.
//!
//! This is a pure data declaration: the `DATASETS` table and the `HkmaDataset`
//! row struct that describes it. The `HkmaConnector` in the parent module
//! derives everything (fetch URLs, `DatasetSpec`s, record-id mapping) from this
//! table. Adding a dataset = adding a row here.
//!
//! See the parent module docs for the section breakdown and the
//! `segment`/`lang` param notes.

use hkgov_common::{Cadence, Category};

/// One row of the verified HKMA dataset table. Adding a dataset = adding a row
/// here; the `Connector` impl derives everything else from the table.
#[derive(Debug, Clone, Copy)]
pub(super) struct HkmaDataset {
    /// Dataset id (the slug used in `/v1/datasets/hkma/<slug>`).
    pub slug: &'static str,
    /// Human-readable title (HKMA bulletin numbering preserved).
    pub title: &'static str,
    /// API path after `/public/`. Verified live.
    pub path: &'static str,
    pub category: Category,
    pub cadence: Cadence,
    pub tags: &'static [&'static str],
    pub refresh_interval_secs: u64,
    /// Some datasets require a `segment` query param (tenor / instrument /
    /// type). When `Some`, the connector sends this exact segment value.
    pub segment: Option<&'static str>,
    /// The `bank-svf-info` family requires `lang=en`. When `true`, the
    /// connector appends `&lang=en`.
    pub lang: bool,
}

impl HkmaDataset {
    /// Render the full fetch URL (path + required query params + pagesize +
    /// offset). HKMA paginates via the `offset` query param (record offset,
    /// not page number); `pagesize=1000` is the upstream max. `offset=0` is
    /// the first page.
    pub fn url(&self, base_url: &str, offset: u64) -> String {
        let mut url = format!("{base_url}/{}?pagesize=1000&offset={offset}", self.path);
        if let Some(seg) = self.segment {
            url.push_str("&segment=");
            url.push_str(seg);
        }
        if self.lang {
            url.push_str("&lang=en");
        }
        url
    }
}

